#!/usr/bin/env node
/**
 * scripts/make-creative-fixtures.mjs — the fixture pack for the published
 * /api/creative contract (docs/creative/fixtures/).
 *
 * Every JSON fixture is the REAL handler's answer, captured against the local
 * SIMULATED Scenario stand-in and then sanitised (ids and timestamps replaced
 * by fixed placeholders; the sha256 values are those of the synthetic images). So the shapes are the application's actual
 * shapes; the provider-side values in them are simulated.
 *
 *   node scripts/make-creative-fixtures.mjs          write the pack
 *   src/lib/creative/fixtures.test.js                fails if the pack is stale
 *
 * The .glb written here is a hand-built box. It is NOT a Scenario output.
 */
import http from "node:http";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const FIXTURE_DIR = path.join(ROOT, "docs/creative/fixtures");
export const SYNTHETIC_GLB_NAME = "SYNTHETIC-box-not-scenario-generated.glb";
export const SYNTHETIC_PNG_NAME = "SYNTHETIC-reference-drawing.png";

const ENV = ["SCENARIO_API_KEY", "SCENARIO_API_SECRET", "SCENARIO_API_BASE_URL", "SCENARIO_3D_MODEL_ID", "SCENARIO_3D_IMAGE_PARAM", "SCENARIO_3D_IMAGE_PARAM_IS_ARRAY", "SCENARIO_3D_EXTRA_PARAMS_JSON", "SCENARIO_STATUS_SUCCESS", "SCENARIO_STATUS_FAILURE", "SCENARIO_LIVE_GENERATION_ENABLED", "SCENARIO_MAX_COST_PER_JOB", "SCENARIO_ASSET_UPLOAD_DATA_URL", "CREATIVE_RECORD_SIGNING_KEY", "FURNIAI_PERSISTENCE_TEST_AUTH", "VERCEL_ENV", "NODE_ENV", "SUPABASE_URL", "SUPABASE_ANON_KEY", "SUPABASE_SERVICE_ROLE_KEY"];

/** A 1.0 × 2.0 × 0.6 box, 24 vertices, one material. Hand-built; no generator service involved. */
export function buildSyntheticGlb() {
  const [x, y, z] = [0.5, 1.0, 0.3];
  const faces = [
    [[0, 0, 1], [[-x, -y, z], [x, -y, z], [x, y, z], [-x, y, z]]],
    [[0, 0, -1], [[x, -y, -z], [-x, -y, -z], [-x, y, -z], [x, y, -z]]],
    [[1, 0, 0], [[x, -y, z], [x, -y, -z], [x, y, -z], [x, y, z]]],
    [[-1, 0, 0], [[-x, -y, -z], [-x, -y, z], [-x, y, z], [-x, y, -z]]],
    [[0, 1, 0], [[-x, y, z], [x, y, z], [x, y, -z], [-x, y, -z]]],
    [[0, -1, 0], [[-x, -y, -z], [x, -y, -z], [x, -y, z], [-x, -y, z]]],
  ];
  const pos = new Float32Array(72);
  const nor = new Float32Array(72);
  const idx = new Uint16Array(36);
  faces.forEach(([n, verts], f) => {
    verts.forEach((v, i) => { pos.set(v, (f * 4 + i) * 3); nor.set(n, (f * 4 + i) * 3); });
    idx.set([0, 1, 2, 0, 2, 3].map((k) => f * 4 + k), f * 6);
  });
  const bin = Buffer.concat([Buffer.from(pos.buffer), Buffer.from(nor.buffer), Buffer.from(idx.buffer)]);
  const gltf = {
    asset: { version: "2.0", generator: "FurniAI synthetic test fixture (hand-built box) — NOT generated by Scenario or any AI model" },
    extras: { synthetic: true, generatedByScenario: false, purpose: "UI wiring fixture for /api/creative", note: "A plain box. Says nothing about what a real Scenario mesh looks like, weighs or contains." },
    scene: 0,
    scenes: [{ nodes: [0] }],
    nodes: [{ mesh: 0, name: "SYNTHETIC_BOX" }],
    meshes: [{ name: "SYNTHETIC_BOX", primitives: [{ attributes: { POSITION: 0, NORMAL: 1 }, indices: 2, material: 0 }] }],
    materials: [{ name: "synthetic-grey", pbrMetallicRoughness: { baseColorFactor: [0.6, 0.6, 0.62, 1], metallicFactor: 0, roughnessFactor: 0.9 } }],
    buffers: [{ byteLength: bin.length }],
    bufferViews: [
      { buffer: 0, byteOffset: 0, byteLength: 288, target: 34962 },
      { buffer: 0, byteOffset: 288, byteLength: 288, target: 34962 },
      { buffer: 0, byteOffset: 576, byteLength: 72, target: 34963 },
    ],
    accessors: [
      { bufferView: 0, componentType: 5126, count: 24, type: "VEC3", min: [-x, -y, -z], max: [x, y, z] },
      { bufferView: 1, componentType: 5126, count: 24, type: "VEC3" },
      { bufferView: 2, componentType: 5123, count: 36, type: "SCALAR" },
    ],
  };
  let json = Buffer.from(JSON.stringify(gltf), "utf8");
  json = Buffer.concat([json, Buffer.alloc((4 - (json.length % 4)) % 4, 0x20)]);
  const header = Buffer.alloc(12);
  header.writeUInt32LE(0x46546c67, 0);
  header.writeUInt32LE(2, 4);
  header.writeUInt32LE(12 + 8 + json.length + 8 + bin.length, 8);
  const chunk = (type, data) => { const h = Buffer.alloc(8); h.writeUInt32LE(data.length, 0); h.writeUInt32LE(type, 4); return Buffer.concat([h, data]); };
  return Buffer.concat([header, chunk(0x4e4f534a, json), chunk(0x004e4942, bin)]);
}

function sanitiser() {
  const ids = new Map();
  const uuid = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi;
  return (value) =>
    JSON.parse(
      JSON.stringify(value)
        .replace(uuid, (m) => { if (!ids.has(m)) ids.set(m, `00000000-0000-4000-8000-${String(ids.size + 1).padStart(12, "0")}`); return ids.get(m); })
        .replace(/\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d{3}Z/g, "2026-10-04T10:00:00.000Z")
        .replace(/https:\/\/cdn\.sim\.invalid\/[^"]+/g, `https://fixtures.invalid/${SYNTHETIC_GLB_NAME}`)
    );
}

/** @returns {Promise<Record<string, object>>} file name → fixture document */
export async function buildFixtures() {
  const saved = Object.fromEntries(ENV.map((k) => [k, process.env[k]]));
  for (const k of ENV) delete process.env[k];
  const imp = (rel) => import(pathToFileURL(path.join(ROOT, rel)).href);
  const { startScenarioStandIn } = await imp("src/lib/creative/scenarioStandIn.js");
  const { getSharedMemoryCreativeStore } = await imp("src/lib/creative/memoryStore.js");
  const { PNG, JPEG, WEBP } = await imp("src/lib/creative/testImages.js");
  const { default: handler } = await imp("api/creative.js");
  const store = getSharedMemoryCreativeStore();
  store._raw.references.clear();
  store._raw.jobs.clear();

  const sim = await startScenarioStandIn();
  const READY = {
    FURNIAI_PERSISTENCE_TEST_AUTH: "yes", SCENARIO_API_KEY: "sim-key", SCENARIO_API_SECRET: "sim-secret", SCENARIO_API_BASE_URL: sim.baseUrl,
    SCENARIO_3D_MODEL_ID: "model_SIMULATED-not-a-real-model-id", SCENARIO_3D_IMAGE_PARAM: "image", SCENARIO_3D_IMAGE_PARAM_IS_ARRAY: "yes",
    SCENARIO_STATUS_SUCCESS: "sim-done", SCENARIO_STATUS_FAILURE: "sim-failed", SCENARIO_LIVE_GENERATION_ENABLED: "yes", SCENARIO_MAX_COST_PER_JOB: "20",
  };
  Object.assign(process.env, READY);
  const api = http.createServer((req, res) => handler(req, res));
  await new Promise((r) => api.listen(0, "127.0.0.1", r));
  const clean = sanitiser();
  const out = {};
  const refuse = (code, body) => async (_q, res) => { res.writeHead(code, { "content-type": "application/json" }); res.end(JSON.stringify(body)); return true; };

  async function hit(name, method, query, body, { auth = true, noteBody } = {}) {
    const r = await fetch(`http://127.0.0.1:${api.address().port}/api/creative?${query}`, {
      method,
      headers: { ...(auth ? { authorization: "Bearer test:fixture-user" } : {}), ...(body ? { "content-type": "application/json" } : {}) },
      body: body ? JSON.stringify(body) : undefined,
    });
    const response = await r.json();
    if (name) {
      out[name] = clean({
        _fixture: { simulated: true, generatedByScenario: false, request: { method, url: `/api/creative?${query}`, ...(body ? { body: noteBody ?? body } : {}) }, httpStatus: r.status },
        response,
      });
    }
    return { status: r.status, body: response };
  }
  const png = { name: "wardrobe.png", contentType: "image/png", dataBase64: PNG.toString("base64") };
  const pngNote = { ...png, dataBase64: `<base64 of ${SYNTHETIC_PNG_NAME}>` };

  try {
    // config
    delete process.env.SCENARIO_3D_MODEL_ID; delete process.env.SCENARIO_LIVE_GENERATION_ENABLED; delete process.env.SCENARIO_MAX_COST_PER_JOB;
    await hit("config.not-ready.200.json", "GET", "resource=config");
    await hit("error.not-configured.503.json", "POST", "resource=jobs", { referenceId: "00000000-0000-4000-8000-00000000aaaa", idempotencyKey: "click-0001" });
    Object.assign(process.env, READY);
    await hit("config.ready.200.json", "GET", "resource=config");
    await hit("error.missing-auth.401.json", "GET", "resource=jobs", null, { auth: false });

    // references
    const up = await hit("reference.created.201.json", "POST", "resource=references", png, { noteBody: pngNote });
    const ref = up.body.reference.referenceId;
    await hit("reference.reused.200.json", "POST", "resource=references", png, { noteBody: pngNote });
    await hit("error.unsupported-file-type.415.json", "POST", "resource=references", { name: "notes.png", dataBase64: Buffer.from("this is text, not an image".padEnd(64)).toString("base64") });
    await hit("error.invalid-image.422.json", "POST", "resource=references", { name: "cut.png", dataBase64: PNG.subarray(0, PNG.length - 20).toString("base64") }, { noteBody: { name: "cut.png", dataBase64: "<base64 of a truncated PNG>" } });

    // gates
    process.env.SCENARIO_LIVE_GENERATION_ENABLED = "no";
    await hit("error.generation-disabled.503.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "click-0001" });
    process.env.SCENARIO_LIVE_GENERATION_ENABLED = "yes";
    sim.state.cost = 21;
    await hit("error.cost-cap-exceeded.402.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "click-0001" });
    sim.state.cost = 12; sim.state.costField = "none";
    await hit("error.cost-unverified.502.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "click-0001" });
    sim.state.costField = "billing";
    await hit("error.missing-reference.404.json", "POST", "resource=jobs", { referenceId: "00000000-0000-4000-8000-00000000aaaa", idempotencyKey: "click-0001" });
    await hit("error.bad-idempotency-key.400.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "x" });

    // job 1 — stays running
    sim.state.pollsUntilDone = 99;
    const j1 = (await hit("job.submitted.202.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "click-0001" })).body.job.jobId;
    await hit("job.replayed.200.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "click-0001" });
    await hit("error.duplicate-active-job.409.json", "POST", "resource=jobs", { referenceId: ref, idempotencyKey: "click-0002" });
    await hit("job.processing.200.json", "GET", `resource=jobs&jobId=${j1}`);
    await hit("error.asset-not-ready.409.json", "GET", `resource=asset&jobId=${j1}`);

    // job 2 — succeeds
    const ref2 = (await hit(null, "POST", "resource=references", { name: "wardrobe.jpg", dataBase64: JPEG.toString("base64") })).body.reference.referenceId;
    await hit("error.idempotency-key-reused.409.json", "POST", "resource=jobs", { referenceId: ref2, idempotencyKey: "click-0001" });
    sim.state.pollsUntilDone = 1;
    const j2 = (await hit(null, "POST", "resource=jobs", { referenceId: ref2, idempotencyKey: "click-0003" })).body.job.jobId;
    await hit("job.succeeded.200.json", "GET", `resource=jobs&jobId=${j2}`);
    await hit("asset.200.json", "GET", `resource=asset&jobId=${j2}&index=0`);
    sim.state.assetGone = true;
    await hit("error.asset-unavailable.410.json", "GET", `resource=asset&jobId=${j2}&index=0`);
    sim.state.assetGone = false;

    // provider refusals on the paid call (each leaves a failed job; none is described as free)
    for (const [file, code, msg, key] of [
      ["error.provider-insufficient-credits.402.json", 402, "Payment required", "click-0004"],
      ["error.provider-rate-limited.429.json", 429, "Too many requests", "click-0005"],
      ["error.provider-rejected-request.502.json", 400, "simulated: input not accepted", "click-0006"],
    ]) {
      sim.state.onGenerate = refuse(code, { message: msg });
      await hit(file, "POST", "resource=jobs", { referenceId: ref2, idempotencyKey: key });
    }
    sim.state.onGenerate = null;
    sim.state.authOk = false;
    await hit("error.provider-auth-rejected.502.json", "POST", "resource=jobs", { referenceId: ref2, idempotencyKey: "click-0007" });
    sim.state.authOk = true;

    // job 3 — provider reports failure
    const ref3 = (await hit(null, "POST", "resource=references", { name: "wardrobe.webp", dataBase64: WEBP.toString("base64") })).body.reference.referenceId;
    sim.state.outcome = "failure";
    const j3 = (await hit(null, "POST", "resource=jobs", { referenceId: ref3, idempotencyKey: "click-0008" })).body.job.jobId;
    await hit("job.failed.200.json", "GET", `resource=jobs&jobId=${j3}`);
    sim.state.outcome = "success";

    // job 4 — the paid call gets no usable answer
    sim.state.onGenerate = refuse(503, { message: "upstream" });
    const unk = await hit("error.provider-unavailable.submission-unknown.502.json", "POST", "resource=jobs", { referenceId: ref3, idempotencyKey: "click-0009" });
    sim.state.onGenerate = null;
    await hit("job.submission-unknown.200.json", "GET", `resource=jobs&jobId=${unk.body.details.jobId}`);
    await hit("error.prior-submission-unknown.409.json", "POST", "resource=jobs", { referenceId: ref3, idempotencyKey: "click-0010" });

    await hit("jobs.list.200.json", "GET", "resource=jobs");
    await hit("error.missing-job.404.json", "GET", "resource=jobs&jobId=00000000-0000-4000-8000-00000000aaaa");
    return out;
  } finally {
    await new Promise((r) => api.close(r));
    await sim.close();
    for (const k of ENV) { if (saved[k] === undefined) delete process.env[k]; else process.env[k] = saved[k]; }
  }
}

const README = `# /api/creative fixture pack

**Everything in this folder is SIMULATED or SYNTHETIC. Nothing here was produced by Scenario.**

- The \`*.json\` files are the real \`/api/creative\` handler's responses, captured against a
  local stand-in for Scenario and sanitised (ids → \`00000000-0000-4000-8000-…\`, timestamps →
  one fixed instant, asset addresses → \`https://fixtures.invalid/…\`). The **shapes** are the
  application contract (docs/creative/SCENARIO_3D_API_CONTRACT.md). Provider-side **values** —
  \`providerStatus\` words such as \`sim-running\`, the model id, costs, \`providerProgress\` — are
  the stand-in's, not Scenario's. Do not build on them; branch on \`status\` and \`code\` only.
- Each file: \`_fixture.request\`, \`_fixture.httpStatus\`, and \`response\` (the body).
- \`${SYNTHETIC_GLB_NAME}\` is a hand-built grey box (24 vertices, 1.0 × 2.0 × 0.6). It exists
  so the viewer and the download button can be wired. It is **not** a Scenario output and says
  nothing about a real mesh's size, topology, materials or quality. \`asset.200.json\` points at
  a placeholder address; serve this file from your mock at whatever address you choose.
- \`${SYNTHETIC_PNG_NAME}\` is a 64×48 drawing made locally for tests — not a photo, not
  customer data.

Regenerate: \`node scripts/make-creative-fixtures.mjs\`. \`src/lib/creative/fixtures.test.js\`
fails when the committed pack no longer matches the handler.
`;

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const fixtures = await buildFixtures();
  const { PNG } = await import(pathToFileURL(path.join(ROOT, "src/lib/creative/testImages.js")).href);
  mkdirSync(FIXTURE_DIR, { recursive: true });
  for (const [name, doc] of Object.entries(fixtures)) writeFileSync(path.join(FIXTURE_DIR, name), JSON.stringify(doc, null, 2) + "\n");
  writeFileSync(path.join(FIXTURE_DIR, SYNTHETIC_GLB_NAME), buildSyntheticGlb());
  writeFileSync(path.join(FIXTURE_DIR, SYNTHETIC_PNG_NAME), PNG);
  writeFileSync(path.join(FIXTURE_DIR, "README.md"), README);
  console.log(`wrote ${Object.keys(fixtures).length} JSON fixtures + ${SYNTHETIC_GLB_NAME} + ${SYNTHETIC_PNG_NAME} + README.md → docs/creative/fixtures/`);
}
