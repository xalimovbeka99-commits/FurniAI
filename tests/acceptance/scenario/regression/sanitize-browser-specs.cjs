// LOCAL regression helper — NOT product code.
// Makes UNTRACKED copies of tests/browser/*.spec.js under
// .qa-sanitized/browser/ (self-ignoring via a generated .qa-sanitized/.gitignore; NOT under test-results/, because Playwright skips its outputDir) with:
//   - every line that copies screenshots into C:/Users/xalim/.gemini/antigravity/brain/...
//     (BRAIN_DIR) removed — this run must never write into any Antigravity folder;
//   - screenshot targets under docs/artifacts/** redirected to
//     test-results/sanitized-artifacts/** (and path.join("docs", …) to
//     test-results/sanitized-docs/…) so tracked evidence files are not rewritten.
// Nothing else is changed. Throws if a BRAIN_DIR / .gemini reference survives.
const fs = require("fs");
const path = require("path");

function sanitizeSource(src, name) {
  let out = src
    .replace(/^const BRAIN_DIR = .*\r?\n/m, "")
    .replace(/try \{\r?\n\s*fs\.mkdirSync\(BRAIN_DIR[^\n]*\r?\n\} catch \(_\) \{\}\r?\n/g, "")
    .replace(/[ \t]*try \{\r?\n\s*fs\.copyFileSync\([^\n]*BRAIN_DIR[^\n]*\r?\n\s*\} catch \(_\) \{\}\r?\n/g, "")
    .replace(/"docs",\s*"artifacts"/g, '"test-results", "sanitized-artifacts"')
    .replace(/(['"`])docs\/artifacts\//g, "$1test-results/sanitized-artifacts/")
    .replace(/path\.join\(\s*"docs",/g, 'path.join("test-results", "sanitized-docs",');
  if (/BRAIN_DIR|\.gemini|antigravity[\\/]+brain/i.test(out)) throw new Error(`sanitize: Antigravity path survived in ${name}`);
  if (/docs\/artifacts|"docs",\s*"artifacts"|path\.join\(\s*"docs"/.test(out)) throw new Error(`sanitize: docs/artifacts write target survived in ${name}`);
  return out;
}

function sanitizeBrowserSpecs(root = process.cwd()) {
  const src = path.join(root, "tests/browser");
  const dst = path.join(root, ".qa-sanitized/browser");
  // Idempotent: the config is evaluated by the runner AND by each worker, so
  // never delete the directory under a running worker; only (re)write files
  // whose content differs and drop files no longer in tests/browser.
  fs.mkdirSync(dst, { recursive: true });
  const ignore = path.join(root, ".qa-sanitized/.gitignore");
  if (!fs.existsSync(ignore)) fs.writeFileSync(ignore, "# generated by sanitize-browser-specs.cjs — never commit\n*\n");
  const changed = [];
  const keep = new Set();
  for (const f of fs.readdirSync(src)) {
    const from = path.join(src, f);
    if (!fs.statSync(from).isFile()) continue;
    const text = fs.readFileSync(from, "utf8");
    const out = f.endsWith(".js") ? sanitizeSource(text, f) : text;
    if (out !== text) changed.push(f);
    keep.add(f);
    const to = path.join(dst, f);
    if (!fs.existsSync(to) || fs.readFileSync(to, "utf8") !== out) fs.writeFileSync(to, out);
  }
  for (const f of fs.readdirSync(dst)) if (!keep.has(f)) fs.rmSync(path.join(dst, f), { recursive: true, force: true });
  return { dir: dst, changed };
}

module.exports = { sanitizeBrowserSpecs, sanitizeSource };
if (require.main === module) console.log(JSON.stringify(sanitizeBrowserSpecs(), null, 2));
